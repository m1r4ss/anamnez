// Что положено по программе диспансеризации (приказ Минздрава № 404н)
export function planFor(age, sex) {
  const f = sex === 'f'
  const rows = []
  if (!age || age < 18) return rows
  if (age >= 40) rows.push(['Диспансеризация', 'каждый год'])
  else if (age % 3 === 0) rows.push(['Диспансеризация', 'в этом году'])
  else rows.push(['Диспансеризация', 'в ' + (age + (3 - (age % 3))) + ' лет'])
  rows.push(['Профилактический осмотр', 'каждый год'])
  if (age >= 35) rows.push(['ЭКГ', 'каждый год'])
  if (age >= 40) rows.push(['Внутриглазное давление', 'каждый год'])
  if (f && age <= 64) rows.push(['Мазок с шейки матки', 'раз в 3 года'])
  if (f && age >= 40 && age <= 75) rows.push(['Маммография', 'раз в 2 года'])
  if (age >= 40 && age <= 64) rows.push(['Тест на скрытую кровь', 'раз в 2 года'])
  if (age >= 65 && age <= 75) rows.push(['Тест на скрытую кровь', 'каждый год'])
  if (!f && [45, 50, 55, 60, 64].includes(age)) rows.push(['Анализ на ПСА', 'в этом году'])
  return rows
}

export const dayOff = (age) => (age >= 40 ? '1 оплачиваемый день каждый год' : '1 оплачиваемый день раз в 3 года')
